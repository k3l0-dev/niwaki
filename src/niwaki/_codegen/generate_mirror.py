"""Generate the public model import mirror — ``niwaki.models.<pkg>.<Cls>``.

Every generated model and enum lives under ``niwaki.models._generated``.  The
documented import path drops that segment::

    from niwaki.models.fv.fvBD import fvBD           # public path
    from niwaki.models._generated.fv.fvBD import fvBD  # canonical path

This generator makes the public path a tree of **real files**, one per
generated module, so that static analysers (mypy, pyright, IDEs) resolve it
exactly like the runtime does:

- a **leaf module** (``fv/fvBD.py``, ``enums/FvBDType.py``) re-exports its
  class with the PEP 484 explicit re-export form
  ``from niwaki.models._generated.fv.fvBD import fvBD as fvBD``;
- a **barrel module** — an underscore-named module such as ``enums/_all.py``
  — re-exports every name its canonical counterpart imports, one explicit
  re-export per line;
- a **package** ``__init__`` (``fv/__init__.py``) carries the same short-name
  table as its canonical counterpart (``BD`` → ``fvBD``) and resolves short
  names lazily through a module ``__getattr__``, so importing the package
  loads none of its classes;
- an **internal package** — an underscore-named package such as
  ``_registers`` (the shared registers of giant named numbers) — holds
  implementation data, not public names: its mirror is an empty placeholder
  package, so the public tree keeps one file per generated module while
  re-exporting nothing internal.

The re-exported objects are the canonical ones: a class keeps its
``__module__`` (``niwaki.models._generated.…``), hence pickles, ``repr`` and
the model REGISTRY are identical whichever path imported it.

The generator is **corpus-free**: its only input is the committed
``_generated`` tree, read as *source* (never imported).  The output is the
exact committed text — every file opens with ``# ruff: noqa`` and
``# fmt: off``, so neither the linter nor the formatter rewrites it.

Usage (from repo root)::

    uv run python -m niwaki._codegen.generate_mirror
"""

from __future__ import annotations

import ast
import shutil
from pathlib import Path

_MODELS_ROOT = Path(__file__).resolve().parent.parent / "models"
_GENERATED_DIRNAME = "_generated"
_CANONICAL_PREFIX = "niwaki.models._generated"
_NOT_MIRROR_DIRS = frozenset({_GENERATED_DIRNAME, "__pycache__"})

_BANNER = """\
# ruff: noqa
# fmt: off
# Generated by niwaki generate_mirror — do not edit manually.
# Re-generate: uv run python -m niwaki._codegen.generate_mirror
"""

_PACKAGE_BODY = """\
from __future__ import annotations

_CLASSES: dict[str, str] = {{
{entries}}}


def __getattr__(name: str) -> type:
    full = _CLASSES.get(name)
    if full is None:
        raise AttributeError(f"module {{__name__!r}} has no attribute {{name!r}}")
    from importlib import import_module

    mod = import_module(f".{{full}}", __name__)
    cls: type = getattr(mod, full)
    globals()[name] = cls
    return cls


__all__ = list(_CLASSES)
"""


class MirrorSourceError(ValueError):
    """A canonical generated module does not have a shape the mirror understands.

    Raised instead of guessing: the mirror must re-export exactly what the
    canonical module exposes, so an unexpected layout (a package ``__init__``
    with code but no short-name table, a relative or star import in a barrel)
    is a generator change to make deliberately.
    """


def _dotted(rel: Path) -> str:
    """``fv/fvBD.py`` → ``fv.fvBD`` ; ``fv/__init__.py`` → ``fv``."""
    parts = rel.with_suffix("").parts
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _is_docstring(node: ast.stmt) -> bool:
    return (
        isinstance(node, ast.Expr)
        and isinstance(node.value, ast.Constant)
        and isinstance(node.value.value, str)
    )


def _is_future_import(node: ast.stmt) -> bool:
    return isinstance(node, ast.ImportFrom) and node.module == "__future__"


def _short_name_table(tree: ast.Module, rel: Path) -> dict[str, str] | None:
    """The literal ``_CLASSES`` table of a canonical package ``__init__``, if any."""
    for node in tree.body:
        match node:
            case ast.AnnAssign(target=ast.Name(id="_CLASSES"), value=value) if value is not None:
                pass
            case ast.Assign(targets=[ast.Name(id="_CLASSES")], value=value):
                pass
            case _:
                continue
        table = ast.literal_eval(value)
        if not isinstance(table, dict) or not all(
            isinstance(k, str) and isinstance(v, str) for k, v in table.items()
        ):
            raise MirrorSourceError(f"{rel}: _CLASSES is not a literal dict[str, str]")
        return {str(k): str(v) for k, v in table.items()}
    return None


def _render_package(tree: ast.Module, rel: Path) -> str:
    table = _short_name_table(tree, rel)
    if table is None and _is_internal_package(rel):
        if _defines_all(tree):
            # An empty placeholder cannot honour a public name list.
            raise MirrorSourceError(f"{rel}: an internal package must not define __all__")
        return _BANNER
    if table is None:
        meaningful = [n for n in tree.body if not (_is_docstring(n) or _is_future_import(n))]
        if meaningful:
            raise MirrorSourceError(
                f"{rel}: package __init__ has code but no _CLASSES short-name table"
            )
        # An empty canonical package (``enums``) mirrors to an empty package:
        # no ``__all__``, nothing to resolve.
        return _BANNER
    if not _defines_all(tree):
        # The mirror's ``__all__`` must equal the canonical one, absence included.
        raise MirrorSourceError(f"{rel}: package __init__ has _CLASSES but no __all__")
    entries = "".join(f'    "{short}": "{full}",\n' for short, full in table.items())
    return f"{_BANNER}{_PACKAGE_BODY.format(entries=entries)}"


def _is_internal_package(rel: Path) -> bool:
    """``_registers/__init__.py``: a package whose directory name is private."""
    return rel.name == "__init__.py" and len(rel.parts) > 1 and rel.parts[-2].startswith("_")


def _defines_all(tree: ast.Module) -> bool:
    return any(
        isinstance(n, ast.Assign)
        and any(isinstance(t, ast.Name) and t.id == "__all__" for t in n.targets)
        for n in tree.body
    )


def _render_barrel(tree: ast.Module, rel: Path) -> str:
    lines: list[str] = []
    for node in tree.body:
        if _is_docstring(node) or _is_future_import(node):
            continue
        if not isinstance(node, ast.ImportFrom) or node.level or node.module is None:
            raise MirrorSourceError(f"{rel}: a barrel may only hold absolute from-imports")
        for alias in node.names:
            if alias.name == "*":
                raise MirrorSourceError(f"{rel}: star imports cannot be re-exported explicitly")
            bound = alias.asname or alias.name
            lines.append(f"from {node.module} import {alias.name} as {bound}\n")
    if not lines:
        raise MirrorSourceError(f"{rel}: barrel re-exports nothing")
    return f"{_BANNER}{''.join(lines)}"


def _render_leaf(rel: Path) -> str:
    stem = rel.stem
    return f"{_BANNER}from {_CANONICAL_PREFIX}.{_dotted(rel)} import {stem} as {stem}\n"


def _render_module(root: Path, rel: Path) -> str:
    """Render one mirror file; only package ``__init__`` files and barrels are parsed.

    The generated layout names every leaf module after the one class it
    defines (``fvBD.py`` → ``fvBD``), so a leaf is rendered from its path
    alone.  Package ``__init__`` files carry the short-name table and
    underscore-named modules (``enums/_all.py``) are barrels — both are read
    as source to re-export exactly what they expose.
    """
    if rel.name != "__init__.py" and not rel.stem.startswith("_"):
        return _render_leaf(rel)
    tree = ast.parse((root / rel).read_text(encoding="utf-8"), filename=str(rel))
    if rel.name == "__init__.py":
        return _render_package(tree, rel)
    return _render_barrel(tree, rel)


def _generated_modules(generated_root: Path) -> list[Path]:
    """Every generated module to mirror, relative to *generated_root*, sorted."""
    return sorted(
        path.relative_to(generated_root)
        for path in generated_root.rglob("*.py")
        if "__pycache__" not in path.parts
        and path.relative_to(generated_root) != Path("__init__.py")
    )


def render_mirror(generated_root: Path | None = None) -> dict[Path, str]:
    """Render the public import mirror of a ``_generated`` tree, without writing it.

    Pure function: the tree is read as source text and parsed with :mod:`ast`
    — never imported — so any tree with the generated layout renders, even a
    synthetic one that could not be imported.

    Args:
        generated_root: The canonical ``_generated`` directory to mirror.
            ``None`` means the package's own ``niwaki/models/_generated``.

    Returns:
        ``{relative path: file text}`` in sorted path order.  Keys are relative
        to the models package directory and equal the generated modules' paths
        relative to *generated_root*: every ``*.py`` except the root
        ``__init__.py`` (the public root is the hand-written
        ``niwaki/models/__init__.py``) and anything under ``__pycache__``.
        Each text is the exact committed file content.

    Raises:
        FileNotFoundError: *generated_root* does not exist or is not a directory.
        MirrorSourceError: A canonical module has a shape the mirror cannot
            re-export faithfully (see :class:`MirrorSourceError`).

    Example:
        >>> mirror = render_mirror()
        >>> print(mirror[Path("fv") / "fvBD.py"].splitlines()[-1])
        from niwaki.models._generated.fv.fvBD import fvBD as fvBD
    """
    root = _MODELS_ROOT / _GENERATED_DIRNAME if generated_root is None else generated_root
    if not root.is_dir():
        raise FileNotFoundError(f"generated tree not found: {root}")
    return {rel: _render_module(root, rel) for rel in _generated_modules(root)}


def _mirror_dirs(models_root: Path) -> list[Path]:
    """Subdirectories of *models_root* that belong to the mirror."""
    return sorted(
        child
        for child in models_root.iterdir()
        if child.is_dir() and child.name not in _NOT_MIRROR_DIRS
    )


def _prune(models_root: Path, keep: set[Path]) -> None:
    """Delete stale mirror modules, then mirror directories left without one."""
    for directory in _mirror_dirs(models_root):
        for path in sorted(directory.rglob("*.py")):
            if "__pycache__" in path.parts:
                continue
            if path.relative_to(models_root) not in keep:
                path.unlink()
        # Deepest first, so a parent emptied by its children's removal goes too.
        # A directory holding anything but a bytecode cache is left alone.
        subdirs = [d for d in directory.rglob("*") if d.is_dir() and "__pycache__" not in d.parts]
        for sub in sorted([directory, *subdirs], key=lambda d: len(d.parts), reverse=True):
            if not any(entry.name != "__pycache__" for entry in sub.iterdir()):
                shutil.rmtree(sub)


def write_mirror(models_root: Path | None = None, generated_root: Path | None = None) -> None:
    """Write the public import mirror and delete stale mirror files.

    Writes :func:`render_mirror` output under *models_root* (a file is only
    rewritten when its content changed), then removes every ``*.py`` inside a
    mirror directory — any subdirectory of *models_root* other than
    ``_generated`` and ``__pycache__`` — that the render no longer produces,
    along with mirror directories left holding nothing but caches.  The
    ``_generated`` tree and the hand-written modules at the models root
    (``__init__.py``, ``base.py``, ``_wire.py``) are never touched.

    Args:
        models_root: Directory receiving the mirror.  ``None`` means the
            package's own ``niwaki/models`` directory.
        generated_root: The canonical tree to mirror.  ``None`` means
            ``models_root / "_generated"``.

    Raises:
        FileNotFoundError: The generated tree does not exist.
        MirrorSourceError: A canonical module cannot be mirrored faithfully.

    Example:
        >>> write_mirror()  # doctest: +SKIP
    """
    models = _MODELS_ROOT if models_root is None else models_root
    generated = models / _GENERATED_DIRNAME if generated_root is None else generated_root
    rendered = render_mirror(generated)
    for rel, text in rendered.items():
        target = models / rel
        if target.is_file() and target.read_text(encoding="utf-8") == text:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    _prune(models, set(rendered))


def main() -> None:
    """Entry point of ``python -m niwaki._codegen.generate_mirror``."""
    write_mirror()
    print(f"model import mirror written under {_MODELS_ROOT}")


if __name__ == "__main__":
    main()
