"""Statically, a carrier takes its naming and nothing else — an attribute is a type error.

A *carrier* (``carrier`` in ``domain/vocabulary.yaml``, today the VMM provider
``vmmProvP``) refuses every non-naming attribute at declaration
(``tests/design/test_carrier_attrs.py``).  The generated typed cursors must say
the same thing to the checker: a call that always raises must not type-check.

* the typed **maker** of a carrier takes the naming parameters only —
  ``design().vmm_provider("VMware", owner_tag="x")`` is a type error;
* the typed cursor's ``set()`` takes **no attribute** —
  ``design().vmm_provider("VMware").set(owner_tag="x")`` is a type error;
* the carrier with its naming, and a child maker beneath it, still type-check.

Why a generated probe, not probes in this file: the repo-wide pyright run
(``scripts/checks.sh --fast``, the pre-commit hook) reads every file under
``tests/``; a probe that is an error only once the generated cursors are fixed
would break that run.  The probe is therefore written to ``tmp_path`` and
checked here only, by both checkers (the convention of
``test_fixed_rn_static.py``):

* **mypy** (repo config, strict, ``warn_unused_ignores``): every refused line
  carries a bare ``# type: ignore`` — the run passes only if each such line is
  an error *of some kind*, and every other line (the valid ones, the imports)
  is clean.  A refused line that type-checks makes its ignore *unused*, which
  is itself the failure;
* **pyright** (repo config, type-ignore comments disabled): the set of lines
  with an error equals the set of ``# expect: error`` markers — the refused
  lines, nothing else.

The rule is deliberately not pinned to one error code: how the generator
removes the keywords (a narrower signature, a ``Never`` catch-all) is its own
business; that an attribute on a carrier does not type-check is the contract.
The probe is built from the vocabulary's carrier set — a carrier curated
tomorrow is probed the day it lands.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from niwaki.design._cursor import _load_class, _tables
from tests.design.test_carrier_attrs import _PROBES, Probe, _carriers, _maker_path

_REPO = Path(__file__).resolve().parents[2]

_IGNORE = "  # type: ignore  # expect: error"
_EXPECT = re.compile(r"# expect: error$")


def _naming_args(aci_class: str) -> str:
    """Positional naming arguments for *aci_class*: ``"x"`` for text, ``1`` for a number."""
    cls = _load_class(aci_class)
    return ", ".join(
        "1" if cls.model_fields[prop].annotation is int else '"x"'
        for prop in cls._naming_props  # pyright: ignore[reportPrivateUsage]
    )


def _chain(aci_class: str, *, stop_before: bool = False) -> str:
    """The typed expression reaching *aci_class* (or its parent) from ``design()``."""
    path = _maker_path(aci_class)
    if stop_before:
        path = path[:-1]
    return "design()" + "".join(f".{label}({_naming_args(child)})" for label, child in path)


def _valid_lines(aci_class: str) -> list[str]:
    """The carrier with its naming, and the first child maker beneath it."""
    child_label, child_class = next(iter(_tables().makers[aci_class].items()))
    return [
        _chain(aci_class),
        f"{_chain(aci_class)}.{child_label}({_naming_args(child_class)})",
    ]


def _refused_lines(aci_class: str) -> list[str]:
    """Every attribute of the carrier, through the typed maker and the typed ``set()``."""
    label, _child = _maker_path(aci_class)[-1]
    lines: list[str] = []
    for probe in (p for p in _PROBES if p.aci_class == aci_class):
        lines.append(_maker_line(aci_class, label, probe))
        lines.append(f"{_chain(aci_class)}.set({probe.field}={probe.value!r})")
    return lines


def _maker_line(aci_class: str, label: str, probe: Probe) -> str:
    """The carrier's typed maker called with its naming *and* one attribute."""
    return (
        f"{_chain(aci_class, stop_before=True)}"
        f".{label}({_naming_args(aci_class)}, {probe.field}={probe.value!r})"
    )


def _probe() -> str:
    """The generated probe module: valid lines clean, refused lines flagged."""
    lines = [
        "# Generated by tests/typing/test_carrier_static.py — a static probe, never run.",
        "from __future__ import annotations",
        "",
        "from niwaki.design import design",
        "",
        "",
        "def _valid() -> None:",
    ]
    for aci_class in _carriers():
        lines += [f"    {line}" for line in _valid_lines(aci_class)]
    lines += ["", "", "def _refused() -> None:"]
    for aci_class in _carriers():
        lines += [f"    {line}{_IGNORE}" for line in _refused_lines(aci_class)]
    return "\n".join(lines) + "\n"


def _expected_error_lines(source: str) -> set[int]:
    return {
        number for number, line in enumerate(source.splitlines(), start=1) if _EXPECT.search(line)
    }


def _pyright_error_lines(path: Path, tmp_path: Path) -> set[int]:
    """Line numbers of every pyright error, type-ignore comments disabled."""
    pyright = shutil.which("pyright")
    if pyright is None:
        pytest.skip("pyright is not installed")
    raw = (_REPO / "pyrightconfig.json").read_text(encoding="utf-8")
    config = json.loads(
        "\n".join(row for row in raw.splitlines() if not row.strip().startswith("//"))
    )
    for key in ("include", "exclude", "executionEnvironments"):
        config.pop(key, None)
    config |= {"venvPath": str(_REPO), "enableTypeIgnoreComments": False}
    (tmp_path / "pyrightconfig.json").write_text(json.dumps(config), encoding="utf-8")
    run = subprocess.run(
        [pyright, "--outputjson", "-p", str(tmp_path / "pyrightconfig.json"), str(path)],
        capture_output=True,
        text=True,
        check=False,
    )
    report = json.loads(run.stdout)
    return {
        diag["range"]["start"]["line"] + 1
        for diag in report["generalDiagnostics"]
        if diag["severity"] == "error"
    }


# ── The probe itself ──────────────────────────────────────────────────────────


def test_the_vocabulary_curates_a_carrier_to_probe() -> None:
    assert _carriers(), "the vocabulary curates no carrier: the probe below would be empty"


def test_the_probe_covers_every_attribute_of_every_carrier_both_ways() -> None:
    probe = _probe()
    assert probe.count(_IGNORE) == 2 * len(_PROBES), "one maker and one set() line per attribute"
    for aci_class in _carriers():
        assert [p for p in _PROBES if p.aci_class == aci_class], aci_class
        assert _valid_lines(aci_class)


# ── The two checkers ──────────────────────────────────────────────────────────


def test_mypy_refuses_an_attribute_on_a_carrier_and_accepts_the_rest(tmp_path: Path) -> None:
    """Every refused line is an error (no ``type: ignore`` goes unused); the rest is clean."""
    api = pytest.importorskip("mypy.api")
    probe = tmp_path / "carrier_probe.py"
    probe.write_text(_probe(), encoding="utf-8")
    stdout, stderr, status = api.run(["--config-file", str(_REPO / "pyproject.toml"), str(probe)])
    assert status == 0, stdout.replace(str(probe), "probe")[:6_000] + stderr


def test_pyright_refuses_an_attribute_on_a_carrier_and_accepts_the_rest(tmp_path: Path) -> None:
    """pyright reports an error on exactly the refused lines."""
    source = _probe()
    probe = tmp_path / "carrier_probe.py"
    probe.write_text(source, encoding="utf-8")
    actual = _pyright_error_lines(probe, tmp_path)
    expected = _expected_error_lines(source)
    lines = source.splitlines()
    missing = sorted(expected - actual)
    unexpected = sorted(actual - expected)
    assert not missing and not unexpected, (
        f"{len(missing)} refused line(s) type-check although they pass an attribute, e.g.:\n"
        + "\n".join(lines[n - 1].strip() for n in missing[:10])
        + f"\n{len(unexpected)} unexpected error line(s): "
        + "; ".join(lines[n - 1].strip() for n in unexpected[:10])
    )
