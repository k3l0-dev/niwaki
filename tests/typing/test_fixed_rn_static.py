"""Statically, a fixed-RN navigation edge takes no name — passing one is a type error.

The runtime refuses a name on a fixed-RN edge (``tests/facade/
test_fixed_rn_navigation.py``): the child has no naming property, so its RN is
fixed and a name could only be silently dropped.  The typed navigation stubs
(``niwaki._generated_nav``, generated by ``niwaki._codegen.generate_nav``)
must say the same thing: the edge is ``def <edge>(self) -> <node>`` — never
the former Rs-singleton shape ``(self, target_name: str = "", **kwargs:
object)``, which let ``epg.custom_qos_policy("gold")`` type-check.

Why a generated probe, not probes in this file: the repo-wide pyright run
(``scripts/checks.sh --fast``, the pre-commit hook) reads every file under
``tests/`` with ``reportUnnecessaryTypeIgnoreComment`` on in the typing
probes; a probe that is an error only once the stubs are fixed would break
that run.  The probe is therefore written to ``tmp_path`` and checked here
only, by both checkers, against its ``# expect:`` markers:

* **mypy** (repo config, strict, ``warn_unused_ignores``): every probe line
  carries ``# type: ignore[call-arg]`` — the run passes only if each line is
  an error of exactly that code (too many arguments / unexpected keyword);
* **pyright** (repo config, type-ignore comments disabled): the set of
  ``(line, rule)`` errors equals the ``# expect:`` markers —
  ``reportCallIssue`` on every probe line, nothing else.

The probe holds a hand-written part (the reported defect and its family:
``custom_qos_policy`` positional / ``target_name=`` / ``name=``,
``vrf_binding``, ``nd_prefix_policy``, a plain singleton, the client's root
proxy, plus the no-argument calls that must stay valid) and an exhaustive
part: every fixed-RN edge of ``CHILD_MAP`` reached from a typed node
(``aci.node(dn, Parent)``, ``aci.root`` for the root row), called with a
positional name, sync and async.
"""

from __future__ import annotations

import importlib
import json
import re
import shutil
import subprocess
from functools import cache
from pathlib import Path
from typing import TYPE_CHECKING, cast

import pytest

from niwaki._codegen.generate_domain import _node_api_names, _root_api_names
from niwaki.domain._child_map import CHILD_MAP, CLASS_PKG, RS_TARGET_PROP

if TYPE_CHECKING:
    from niwaki.models.base import ManagedObject

_REPO = Path(__file__).resolve().parents[2]

_IGNORE = "  # type: ignore[call-arg]  # expect: reportCallIssue"


@cache
def _model(aci_class: str) -> type[ManagedObject]:
    module = importlib.import_module(f"niwaki.models._generated.{CLASS_PKG[aci_class]}.{aci_class}")
    return cast("type[ManagedObject]", getattr(module, aci_class))


@cache
def _fixed_edges() -> tuple[tuple[str, str, str], ...]:
    """Every reachable ``(parent, edge, child)`` whose child has no naming prop, sorted."""
    edges: list[tuple[str, str, str]] = []
    for parent in sorted(CHILD_MAP):
        if parent != "_root" and parent not in CLASS_PKG:
            continue
        reserved = _root_api_names() | _node_api_names() if parent == "_root" else _node_api_names()
        for edge, child in sorted(CHILD_MAP[parent].items()):
            if edge in reserved or child not in CLASS_PKG:
                continue
            if not _model(child)._naming_props:  # pyright: ignore[reportPrivateUsage]
                edges.append((parent, edge, child))
    return tuple(edges)


_HAND_WRITTEN = """
def _hand_written(aci: Niwaki, aaci: AsyncNiwaki) -> None:
    epg = aci.tenant("prod").app("shop").epg("web")
    # No argument stays valid: the fixed RN.
    assert_type(epg.custom_qos_policy(), NavLeaf[fvRsCustQosPol])
    assert_type(aci.tenant("prod").bd("web").vrf_binding(), fvRsCtxNode)
    assert_type(aci.infra(), infraInfraNode)
    # The reported defect: every way of passing the ignored name.
    epg.custom_qos_policy("gold"){ignore}
    epg.custom_qos_policy(target_name="gold"){ignore}
    epg.custom_qos_policy(name="gold"){ignore}
    epg.custom_qos_policy(""){ignore}
    bd = aci.tenant("prod").bd("web")
    bd.vrf_binding("prod"){ignore}
    bd.vrf_binding(target_name="prod"){ignore}
    bd.subnet(subnet="10.0.0.1/24").nd_prefix_policy("ra"){ignore}
    # A plain (non-Rs) fixed-RN edge, and the client's root proxy.
    bd.legacy_mode(name="x"){ignore}
    aci.infra("x"){ignore}
    # Async twins.
    aepg = aaci.tenant("prod").app("shop").epg("web")
    assert_type(aepg.custom_qos_policy(), AsyncNavLeaf[fvRsCustQosPol])
    aepg.custom_qos_policy("gold"){ignore}
    aepg.custom_qos_policy(target_name="gold"){ignore}
    aaci.tenant("prod").bd("web").vrf_binding("prod"){ignore}
"""


def _probe() -> str:
    edges = _fixed_edges()
    parents = sorted({parent for parent, _edge, _child in edges if parent != "_root"})
    lines = [
        "# Generated by tests/typing/test_fixed_rn_static.py — a static probe, never run.",
        "from __future__ import annotations",
        "",
        "from typing import assert_type",
        "",
        "from niwaki import AsyncNiwaki, Niwaki",
        "from niwaki._generated_nav import AsyncNavLeaf, NavLeaf",
        "from niwaki._generated_nav.fv import fvRsCtxNode",
        "from niwaki._generated_nav.infra import infraInfraNode",
        "from niwaki.models._generated.fv.fvRsCustQosPol import fvRsCustQosPol",
    ]
    lines += [f"from niwaki.models._generated.{CLASS_PKG[p]}.{p} import {p}" for p in parents]
    lines.append("")
    lines += _HAND_WRITTEN.format(ignore=_IGNORE).splitlines()
    lines += ["", "", "def _exhaustive(aci: Niwaki, aaci: AsyncNiwaki) -> None:"]
    for parent, edge, _child in edges:
        for client in ("aci", "aaci"):
            node = f"{client}.root" if parent == "_root" else f"{client}.node('uni/x', {parent})"
            lines.append(f'    {node}.{edge}("gold"){_IGNORE}')
    return "\n".join(lines) + "\n"


_EXPECT = re.compile(r"# expect: ([\w, ]+)$")


def _expected_pyright_errors(source: str) -> set[tuple[int, str]]:
    return {
        (number, rule.strip())
        for number, line in enumerate(source.splitlines(), start=1)
        if (match := _EXPECT.search(line))
        for rule in match.group(1).split(",")
    }


def _pyright_errors(path: Path, tmp_path: Path) -> set[tuple[int, str]]:
    """(line, rule) of every pyright error, type-ignore comments disabled."""
    pyright = shutil.which("pyright")
    if pyright is None:
        pytest.skip("pyright is not installed")
    raw = (_REPO / "pyrightconfig.json").read_text(encoding="utf-8")
    config = json.loads(
        "\n".join(row for row in raw.splitlines() if not row.strip().startswith("//"))
    )
    for key in ("include", "exclude", "executionEnvironments"):
        config.pop(key, None)
    config |= {"venvPath": str(_REPO), "enableTypeIgnoreComments": False}
    (tmp_path / "pyrightconfig.json").write_text(json.dumps(config), encoding="utf-8")
    run = subprocess.run(
        [pyright, "--outputjson", "-p", str(tmp_path / "pyrightconfig.json"), str(path)],
        capture_output=True,
        text=True,
        check=False,
    )
    report = json.loads(run.stdout)
    return {
        (diag["range"]["start"]["line"] + 1, diag.get("rule", "?"))
        for diag in report["generalDiagnostics"]
        if diag["severity"] == "error"
    }


# ── The probe itself ──────────────────────────────────────────────────────────


def test_probe_covers_every_fixed_rn_edge_and_both_families() -> None:
    probe = _probe()
    edges = _fixed_edges()
    assert len(edges) > 1_000, "the fixed-RN sweep was thinned out"
    assert sum(child in RS_TARGET_PROP for _p, _e, child in edges) > 100
    assert probe.count(_IGNORE) == 2 * len(edges) + _HAND_WRITTEN.count("{ignore}")
    assert "aci.node('uni/x', fvAEPg).custom_qos_policy(\"gold\")" in probe
    assert "aci.node('uni/x', fvBD).pim(\"gold\")" in probe
    assert 'aci.root.infra("gold")' in probe


# ── The two checkers ──────────────────────────────────────────────────────────


def test_mypy_refuses_a_name_on_every_fixed_rn_edge(tmp_path: Path) -> None:
    """Every probe line is a ``call-arg`` error: no ``type: ignore`` goes unused."""
    api = pytest.importorskip("mypy.api")
    probe = tmp_path / "fixed_rn_probe.py"
    probe.write_text(_probe(), encoding="utf-8")
    stdout, stderr, status = api.run(["--config-file", str(_REPO / "pyproject.toml"), str(probe)])
    assert status == 0, stdout.replace(str(probe), "probe")[:6_000] + stderr


def test_pyright_refuses_a_name_on_every_fixed_rn_edge(tmp_path: Path) -> None:
    """pyright reports ``reportCallIssue`` on exactly the probe lines."""
    source = _probe()
    probe = tmp_path / "fixed_rn_probe.py"
    probe.write_text(source, encoding="utf-8")
    actual = _pyright_errors(probe, tmp_path)
    expected = _expected_pyright_errors(source)
    lines = source.splitlines()
    missing = sorted(expected - actual)
    unexpected = sorted(actual - expected)
    assert not missing and not unexpected, (
        f"{len(missing)} probe line(s) type-check although they pass a name, e.g.:\n"
        + "\n".join(lines[n - 1].strip() for n, _rule in missing[:15])
        + f"\n{len(unexpected)} unexpected error(s): {unexpected[:15]}"
    )
