"""The navigation stubs are generated, corpus-free, fresh, wired, and shipped.

The typed navigation stubs (``src/niwaki/_generated_nav/*.pyi``) are emitted by
``niwaki._codegen.generate_nav``.  Their inputs are all committed —
``niwaki.domain._child_map`` (``CHILD_MAP``, ``CLASS_PKG``,
``RS_TARGET_PROP``) and the generated models (naming props, field
annotations) — so, unlike the model generator, their rebuild-and-compare guard
needs no schema corpus and runs everywhere, the public CI included.

Generator contract pinned here
------------------------------

``render_nav() -> dict[Path, str]``
    Pure function: computes every stub file without writing anything.  Keys
    are paths relative to the stub package directory, sorted:
    ``Path("__init__.pyi")``, ``Path("_base.pyi")``, ``Path("_root.pyi")`` and
    one ``Path("<pkg>.pyi")`` per ACI class package holding a typed parent —
    never a ``.py`` (a single ``.py`` would make the stub package importable
    at runtime).  Each value is the **exact committed text**: already
    ruff-clean and ruff-formatted (``regen.sh`` does not reformat it),
    starting with a comment block that carries the usual "Generated by …
    do not edit manually" banner and, in every file that uses ``@overload``,
    ``# mypy: disable-error-code="overload-overlap"``; it ends with a newline.
    Deterministic: two calls return equal dicts in the same key order.

``write_nav(nav_dir: Path | None = None) -> None``
    Writes :func:`render_nav` under *nav_dir* (``None`` → the package's own
    ``src/niwaki/_generated_nav``), creating the directory when missing and
    rewriting a file only when its content changed; then deletes every
    ``*.pyi`` in *nav_dir* that the render no longer produces.  It never
    writes a ``.py``.  Idempotent.

``python -m niwaki._codegen.generate_nav``
    Calls ``write_nav()``; wired into ``scripts/regen.sh`` after
    ``generate_design`` (the stubs reuse its ``_param_type``) and before the
    freshness manifest write.  Every stub is a recorded artifact of the
    freshness manifest, and ``generate_nav.py`` one of its inputs.

The wheel ships the stubs (they are ``py.typed`` package data under
``src/niwaki``); the measure is taken on the source tree with
``tests/_package_weight.py`` and, on the private gate, by ``wheel_smoke.py``
against a pristine install of the built wheel.
"""

from __future__ import annotations

import importlib
import inspect
from collections.abc import Callable
from pathlib import Path
from types import ModuleType
from typing import cast

import pytest

import niwaki
from niwaki._codegen import freshness
from tests._package_weight import read_wheel_layout, shipped_files

_NAV_DIR = Path(niwaki.__file__).resolve().parent / "_generated_nav"
_REPO = Path(niwaki.__file__).resolve().parents[2]

_RenderNav = Callable[[], dict[Path, str]]
_WriteNav = Callable[..., None]


def _generator() -> ModuleType:
    """Import the generator inside each test, so this module always collects."""
    return importlib.import_module("niwaki._codegen.generate_nav")


@pytest.fixture(scope="module")
def rendered() -> dict[Path, str]:
    """One render shared by the module (it imports ~2,000 models the first time)."""
    return cast(_RenderNav, _generator().render_nav)()


def _write() -> _WriteNav:
    return cast(_WriteNav, _generator().write_nav)


def _committed() -> dict[Path, str]:
    return {
        path.relative_to(_NAV_DIR): path.read_text(encoding="utf-8")
        for path in sorted(_NAV_DIR.iterdir())
        if path.is_file() and path.suffix in {".py", ".pyi"}
    }


# ── Rebuild-and-compare (corpus-free) ─────────────────────────────────────────


def test_committed_stubs_match_a_fresh_render(rendered: dict[Path, str]) -> None:
    """Byte-equal: a hand edit or a forgotten regen fails here, on any machine."""
    committed = _committed()
    missing = sorted(map(str, set(rendered) - set(committed)))
    stale = sorted(map(str, set(committed) - set(rendered)))
    drifted = sorted(str(p) for p in set(rendered) & set(committed) if rendered[p] != committed[p])
    assert not (missing or stale or drifted), (
        "the committed navigation stubs diverged from a fresh render "
        "(run `uv run python -m niwaki._codegen.generate_nav`):\n"
        f"  missing ({len(missing)}): {missing[:5]}\n"
        f"  stale   ({len(stale)}): {stale[:5]}\n"
        f"  drifted ({len(drifted)}): {drifted[:5]}"
    )


def test_render_emits_stubs_only(rendered: dict[Path, str]) -> None:
    assert rendered, "render_nav() rendered nothing"
    assert all(path.suffix == ".pyi" for path in rendered), sorted(map(str, rendered))
    assert all(len(path.parts) == 1 for path in rendered), "the stub package is flat"
    assert {Path("__init__.pyi"), Path("_base.pyi"), Path("_root.pyi"), Path("fv.pyi")} <= set(
        rendered
    )


def test_render_keys_are_sorted(rendered: dict[Path, str]) -> None:
    assert list(rendered) == sorted(rendered)


def test_render_is_deterministic(rendered: dict[Path, str]) -> None:
    again = cast(_RenderNav, _generator().render_nav)()
    assert again == rendered
    assert list(again) == list(rendered), "key order must be stable too"


def test_every_rendered_file_carries_the_banner_and_ends_with_a_newline(
    rendered: dict[Path, str],
) -> None:
    bad = [
        str(path)
        for path, text in rendered.items()
        if not (
            text.startswith("#")
            and "Generated by" in text
            and "do not edit manually" in text
            and text.endswith("\n")
        )
    ]
    assert not bad, bad[:5]


# ── write_nav on a scratch directory (nominal, edge, idempotence) ─────────────


def test_write_nav_writes_the_render_and_prunes_stale_stubs(
    tmp_path: Path, rendered: dict[Path, str]
) -> None:
    nav = tmp_path / "_generated_nav"
    nav.mkdir()
    stale = nav / "zzgone.pyi"
    stale.write_text("# stale\n", encoding="utf-8")
    cache = nav / "__pycache__"
    cache.mkdir()
    (cache / "keep.pyc").write_bytes(b"\x00")

    _write()(nav)

    for rel, text in rendered.items():
        assert (nav / rel).read_text(encoding="utf-8") == text
    assert not stale.exists(), "a stub the render no longer produces must be deleted"
    assert not list(nav.rglob("*.py")), "write_nav must never write a .py"
    assert {p.relative_to(nav) for p in nav.glob("*.pyi")} == set(rendered)


def test_write_nav_creates_a_missing_directory(tmp_path: Path, rendered: dict[Path, str]) -> None:
    nav = tmp_path / "deep" / "_generated_nav"
    _write()(nav)
    assert {p.relative_to(nav) for p in nav.glob("*.pyi")} == set(rendered)


def test_write_nav_is_idempotent(tmp_path: Path) -> None:
    nav = tmp_path / "_generated_nav"
    write = _write()
    write(nav)
    first = {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in nav.glob("*.pyi")}
    write(nav)
    second = {p: (p.read_bytes(), p.stat().st_mtime_ns) for p in nav.glob("*.pyi")}
    assert second == first, "an unchanged file must not be rewritten"


def test_generator_public_functions_are_documented() -> None:
    module = _generator()
    for name in ("render_nav", "write_nav"):
        doc = inspect.getdoc(getattr(module, name)) or ""
        assert len(doc) > 80, f"{name} needs a verbose docstring (Args/Returns/Raises)"
    assert inspect.getdoc(module), "generate_nav needs a module docstring"
    assert callable(getattr(module, "main", None)), "python -m entry point missing"


# ── Wiring: regen pipeline and freshness manifest ─────────────────────────────


def test_regen_pipeline_runs_the_nav_generator_after_the_cursors() -> None:
    regen = _REPO / "scripts" / "regen.sh"
    if not regen.is_file():
        pytest.skip("scripts/regen.sh not present in this distribution")
    text = regen.read_text(encoding="utf-8")
    call = "niwaki._codegen.generate_nav"
    assert call in text, "regen.sh does not run the navigation stub generator"
    position = text.index(call)
    assert text.index("niwaki._codegen.generate_domain") < position
    assert text.index("niwaki._codegen.generate_design") < position
    assert position < text.index("niwaki._codegen.freshness --write")


def test_the_nav_generator_is_a_manifest_input() -> None:
    assert "generate_nav.py" in {path.name for path in freshness._input_files()}


def test_every_stub_is_a_manifest_artifact(rendered: dict[Path, str]) -> None:
    artifacts = {path.resolve() for path in freshness._artifact_files()}
    missing = sorted(str(rel) for rel in rendered if (_NAV_DIR / rel).resolve() not in artifacts)
    assert not missing, f"stubs not recorded in freshness._artifact_files(): {missing[:5]}"
    files = [path.resolve() for path in freshness._artifact_files()]
    assert len(files) == len(set(files)), "an artifact is listed twice"


# ── Packaging ─────────────────────────────────────────────────────────────────


def test_the_wheel_ships_every_stub(rendered: dict[Path, str]) -> None:
    """The stubs are package files under ``src/niwaki``, not excluded from the wheel."""
    shipped = {path.resolve() for path in shipped_files(read_wheel_layout())}
    missing = sorted(str(rel) for rel in rendered if (_NAV_DIR / rel).resolve() not in shipped)
    assert not missing, f"stubs left out of the wheel: {missing[:5]}"


def test_the_package_is_marked_typed() -> None:
    """Without ``py.typed`` an installed niwaki's stubs are ignored by checkers."""
    assert (_NAV_DIR.parent / "py.typed").is_file()
    shipped = {path.resolve() for path in shipped_files(read_wheel_layout())}
    assert (_NAV_DIR.parent / "py.typed").resolve() in shipped
