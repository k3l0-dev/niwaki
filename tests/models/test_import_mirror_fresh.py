"""The model import mirror is generated, corpus-free, and fresh.

The mirror (``src/niwaki/models/<pkg>/<Cls>.py`` re-exporting
``niwaki.models._generated.<pkg>.<Cls>``) is emitted by
``niwaki._codegen.generate_mirror``.  Its only input is the committed
``_generated`` tree, so — unlike the model generator, which needs the 1.7 GB
schema corpus — its rebuild-and-compare guard runs everywhere, the public CI
included.

Generator contract pinned here
------------------------------

``render_mirror(generated_root: Path | None = None) -> dict[Path, str]``
    Pure function.  Reads the ``_generated`` tree *from source on disk* (it
    must not import it: a synthetic tree in a temp directory renders too) and
    returns ``{relative path: file text}``.  Keys are relative to the models
    package directory (``src/niwaki/models``) and equal the paths of the
    generated modules relative to ``_generated`` — every ``*.py`` under it
    except the root ``__init__.py`` (the public root is the hand-written
    ``niwaki/models/__init__.py``) and anything under ``__pycache__``.
    ``None`` means the package's own ``_generated`` directory.  The text is
    the exact committed text (``regen.sh`` does not need to reformat it),
    starts with ``# ruff: noqa``, carries the usual "Generated by … do not
    edit manually" banner, and ends with a newline.  A leaf module re-exports
    its class with the explicit-re-export form
    ``from niwaki.models._generated.<pkg>.<Cls> import <Cls> as <Cls>``.
    A missing ``generated_root`` raises :class:`FileNotFoundError`.

``write_mirror(models_root: Path | None = None, generated_root: Path | None = None) -> None``
    Writes ``render_mirror(generated_root)`` under ``models_root`` (``None`` →
    the package's models directory; ``generated_root`` ``None`` →
    ``models_root / "_generated"``) and deletes stale ``*.py`` mirror files —
    files inside mirror directories (subdirectories of ``models_root`` other
    than ``_generated`` and ``__pycache__``) that the render no longer
    produces.  It never touches ``_generated`` nor the hand-written files at
    the models root (``__init__.py``, ``base.py``, ``_wire.py``).

``python -m niwaki._codegen.generate_mirror``
    Calls ``write_mirror()``; wired into ``scripts/regen.sh`` after the model
    and enum generators and before the manifest write.
"""

from __future__ import annotations

import ast
import importlib
import inspect
from collections.abc import Callable
from pathlib import Path
from types import ModuleType
from typing import cast

import pytest

import niwaki.models
from niwaki._codegen import freshness

_MODELS = Path(niwaki.models.__file__).resolve().parent
_GENERATED = _MODELS / "_generated"
_REPO = _MODELS.parents[2]

_RenderMirror = Callable[..., dict[Path, str]]
_WriteMirror = Callable[..., None]


def _generator() -> ModuleType:
    """Import the generator inside each test, so this module always collects."""
    return importlib.import_module("niwaki._codegen.generate_mirror")


def _render() -> _RenderMirror:
    return cast(_RenderMirror, _generator().render_mirror)


def _write() -> _WriteMirror:
    return cast(_WriteMirror, _generator().write_mirror)


def _expected_paths() -> set[Path]:
    """The mirror's key set, derived independently of the generator."""
    return {
        path.relative_to(_GENERATED)
        for path in _GENERATED.rglob("*.py")
        if "__pycache__" not in path.parts and path.relative_to(_GENERATED) != Path("__init__.py")
    }


def _committed_mirror() -> dict[Path, str]:
    return {
        path.relative_to(_MODELS): path.read_text(encoding="utf-8")
        for child in sorted(_MODELS.iterdir())
        if child.is_dir() and child.name not in {"_generated", "__pycache__"}
        for path in child.rglob("*.py")
        if "__pycache__" not in path.parts
    }


# ── Rebuild-and-compare on the real tree (corpus-free) ────────────────────────


def test_render_covers_exactly_the_generated_tree() -> None:
    rendered = _render()()
    expected = _expected_paths()
    assert set(rendered) == expected, (
        f"missing: {sorted(map(str, expected - set(rendered)))[:5]}, "
        f"extra: {sorted(map(str, set(rendered) - expected))[:5]}"
    )
    assert len(rendered) > 3_000


def test_committed_mirror_matches_a_fresh_render() -> None:
    """Byte-equal: a hand edit or a forgotten regen fails here, on any machine."""
    rendered = _render()()
    committed = _committed_mirror()
    missing = sorted(map(str, set(rendered) - set(committed)))
    stale = sorted(map(str, set(committed) - set(rendered)))
    drifted = sorted(str(p) for p in set(rendered) & set(committed) if rendered[p] != committed[p])
    assert not (missing or stale or drifted), (
        "the committed mirror diverged from a fresh render "
        "(run `uv run python -m niwaki._codegen.generate_mirror`):\n"
        f"  missing ({len(missing)}): {missing[:5]}\n"
        f"  stale   ({len(stale)}): {stale[:5]}\n"
        f"  drifted ({len(drifted)}): {drifted[:5]}"
    )


def test_render_is_deterministic() -> None:
    render = _render()
    first, second = render(), render()
    assert first == second
    assert list(first) == list(second), "key order must be stable too"


def test_default_root_is_the_package_generated_tree() -> None:
    render = _render()
    assert render() == render(_GENERATED)


def test_every_rendered_file_carries_the_generated_banner() -> None:
    bad = [
        str(path)
        for path, text in _render()().items()
        if not (
            text.startswith("# ruff: noqa\n")
            and "Generated by" in text
            and "do not edit manually" in text
            and text.endswith("\n")
        )
    ]
    assert not bad, f"files without the generated banner / final newline: {bad[:5]}"


def test_leaf_model_module_is_an_explicit_reexport() -> None:
    text = _render()()[Path("fv") / "fvBD.py"]
    assert "from niwaki.models._generated.fv.fvBD import fvBD as fvBD\n" in text


def test_leaf_enum_module_is_an_explicit_reexport() -> None:
    text = _render()()[Path("enums") / "FvBDType.py"]
    assert "from niwaki.models._generated.enums.FvBDType import FvBDType as FvBDType\n" in text


def test_enum_barrel_reexports_every_enum() -> None:
    text = _render()()[Path("enums") / "_all.py"]
    enums = sorted(
        p.stem
        for p in (_GENERATED / "enums").glob("*.py")
        if p.name not in {"__init__.py", "_all.py"}
    )
    missing = [name for name in enums if f"import {name} as {name}\n" not in text]
    assert not missing, f"enums barrel misses explicit re-exports for: {missing[:5]}"


def test_the_root_package_is_never_rendered() -> None:
    """``niwaki/models/__init__.py`` is hand-written (base, REGISTRY) — never overwritten."""
    rendered = _render()()
    assert Path("__init__.py") not in rendered
    assert not any(path.parts[0] == "_generated" for path in rendered)


# ── The generator on a synthetic tree (nominal, edge, error) ──────────────────

_SYNTH_ROOT_INIT = '_PKG_MAP: dict[str, str] = {"xyFoo": "xy", "xyBar": "xy"}\n'
_SYNTH_PKG_INIT = (
    '_CLASSES: dict[str, str] = {\n    "Bar": "xyBar",\n    "Foo": "xyFoo",\n}\n\n\n'
    "def __getattr__(name: str) -> type:\n"
    "    raise AttributeError(name)\n\n\n"
    "__all__ = list(_CLASSES)\n"
)


def _synthetic_generated(root: Path) -> Path:
    """A miniature ``_generated`` tree with the real layout."""
    gen = root / "_generated"
    (gen / "xy" / "__pycache__").mkdir(parents=True)
    (gen / "enums").mkdir()
    (gen / "__init__.py").write_text(_SYNTH_ROOT_INIT, encoding="utf-8")
    (gen / "xy" / "__init__.py").write_text(_SYNTH_PKG_INIT, encoding="utf-8")
    (gen / "xy" / "xyFoo.py").write_text("class xyFoo: ...\n", encoding="utf-8")
    (gen / "xy" / "xyBar.py").write_text("class xyBar: ...\n", encoding="utf-8")
    (gen / "xy" / "__pycache__" / "xyFoo.cpython-312.pyc").write_bytes(b"\x00")
    (gen / "xy" / "notes.txt").write_text("not a module\n", encoding="utf-8")
    (gen / "enums" / "__init__.py").write_text("", encoding="utf-8")
    (gen / "enums" / "XyMode.py").write_text(
        "from enum import StrEnum\n\n\nclass XyMode(StrEnum):\n    A = 'a'\n", encoding="utf-8"
    )
    (gen / "enums" / "_all.py").write_text(
        "from niwaki.models._generated.enums.XyMode import XyMode\n", encoding="utf-8"
    )
    return gen


_SYNTH_KEYS = {
    Path("xy") / "__init__.py",
    Path("xy") / "xyFoo.py",
    Path("xy") / "xyBar.py",
    Path("enums") / "__init__.py",
    Path("enums") / "XyMode.py",
    Path("enums") / "_all.py",
}


def test_render_on_a_synthetic_tree(tmp_path: Path) -> None:
    """Nominal: one file per module; caches, non-modules and the root are skipped."""
    rendered = _render()(_synthetic_generated(tmp_path))
    assert set(rendered) == _SYNTH_KEYS
    assert (
        "from niwaki.models._generated.xy.xyFoo import xyFoo as xyFoo\n"
        in (rendered[Path("xy") / "xyFoo.py"])
    )
    assert (
        "from niwaki.models._generated.xy.xyBar import xyBar as xyBar\n"
        in (rendered[Path("xy") / "xyBar.py"])
    )
    assert (
        "from niwaki.models._generated.enums.XyMode import XyMode as XyMode\n"
        in (rendered[Path("enums") / "XyMode.py"])
    )
    assert "import XyMode as XyMode\n" in rendered[Path("enums") / "_all.py"]


def test_render_package_init_resolves_short_names_lazily(tmp_path: Path) -> None:
    """The package ``__init__`` knows the short names and resolves them in ``__getattr__``.

    Runtime laziness itself (no class module loaded by importing the package)
    is pinned on the real tree in ``test_import_mirror.py``.
    """
    text = _render()(_synthetic_generated(tmp_path))[Path("xy") / "__init__.py"]
    assert "def __getattr__(" in text
    assert "__all__" in text
    for short, full in (("Foo", "xyFoo"), ("Bar", "xyBar")):
        assert f'"{short}"' in text and f'"{full}"' in text


def test_render_does_not_import_the_tree(tmp_path: Path) -> None:
    """A synthetic tree is not importable — rendering it proves source-reading."""
    gen = _synthetic_generated(tmp_path)
    (gen / "xy" / "xyFoo.py").write_text("raise RuntimeError('imported!')\n", encoding="utf-8")
    assert Path("xy") / "xyFoo.py" in _render()(gen)


def test_render_missing_root_fails_loud(tmp_path: Path) -> None:
    with pytest.raises(FileNotFoundError):
        _render()(tmp_path / "no-such-generated-tree")


def test_write_mirror_writes_and_prunes(tmp_path: Path) -> None:
    """Rendered files land; stale mirror files go; hand-written files stay."""
    gen = _synthetic_generated(tmp_path)
    models = tmp_path
    hand_written = {
        models / "__init__.py": "# hand-written root\n",
        models / "base.py": "# hand-written base\n",
        models / "_wire.py": "# hand-written wire\n",
    }
    for path, text in hand_written.items():
        path.write_text(text, encoding="utf-8")
    stale_leaf = models / "xy" / "xyGone.py"
    stale_pkg = models / "zz" / "__init__.py"
    stale_pkg_leaf = models / "zz" / "zzOld.py"
    for path in (stale_leaf, stale_pkg, stale_pkg_leaf):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("# stale\n", encoding="utf-8")
    generated_before = {p: p.read_bytes() for p in gen.rglob("*") if p.is_file()}

    _write()(models, gen)

    rendered = _render()(gen)
    for rel, text in rendered.items():
        assert (models / rel).read_text(encoding="utf-8") == text
    assert not stale_leaf.exists()
    assert not stale_pkg.exists()
    assert not stale_pkg_leaf.exists()
    for path, text in hand_written.items():
        assert path.read_text(encoding="utf-8") == text, f"{path.name} was touched"
    assert {p: p.read_bytes() for p in gen.rglob("*") if p.is_file()} == generated_before


def test_write_mirror_is_idempotent(tmp_path: Path) -> None:
    gen = _synthetic_generated(tmp_path)
    write = _write()
    write(tmp_path, gen)
    first = {p: p.read_bytes() for p in tmp_path.rglob("*.py")}
    write(tmp_path, gen)
    assert {p: p.read_bytes() for p in tmp_path.rglob("*.py")} == first


def test_generator_public_functions_are_documented() -> None:
    module = _generator()
    for name in ("render_mirror", "write_mirror"):
        func = getattr(module, name)
        doc = inspect.getdoc(func) or ""
        assert len(doc) > 80, f"{name} needs a verbose docstring (Args/Returns/Raises)"
    assert inspect.getdoc(module), "generate_mirror needs a module docstring"


# ── Wiring: regen pipeline and freshness manifest ─────────────────────────────


def test_regen_pipeline_runs_the_mirror_generator_in_order() -> None:
    regen = _REPO / "scripts" / "regen.sh"
    if not regen.is_file():
        pytest.skip("scripts/regen.sh not present in this distribution")
    text = regen.read_text(encoding="utf-8")
    call = "niwaki._codegen.generate_mirror"
    assert call in text, "regen.sh does not run the mirror generator"
    position = text.index(call)
    assert text.index("niwaki._codegen.generate_enums") < position
    assert text.index("niwaki._codegen.generate\n") < position
    assert position < text.index("niwaki._codegen.freshness --write")


def test_the_mirror_generator_is_a_manifest_input() -> None:
    assert "generate_mirror.py" in {path.name for path in freshness._input_files()}


def test_every_mirror_file_is_a_manifest_artifact() -> None:
    artifacts = {path.resolve() for path in freshness._artifact_files()}
    missing = sorted(str(rel) for rel in _expected_paths() if (_MODELS / rel) not in artifacts)
    assert not missing, (
        f"{len(missing)} mirror files are not recorded artifacts in freshness._artifact_files() "
        f"(first: {missing[:5]})"
    )


def test_artifact_files_are_unique_and_exclude_hand_written_models() -> None:
    """Mirror globbing must neither double-count ``_generated`` nor swallow base/_wire."""
    files = [path.resolve() for path in freshness._artifact_files()]
    assert len(files) == len(set(files)), "an artifact is listed twice"
    for hand_written in ("__init__.py", "base.py", "_wire.py"):
        assert (_MODELS / hand_written) not in set(files), (
            f"models/{hand_written} is hand-written, not a regen artifact"
        )


# ── Generated docs speak the public path, never the internal one ──────────────

_INTERNAL_PATH = "niwaki.models._generated"
_VOCABULARY_BOOK = _REPO / "docs" / "reference" / "vocabulary"
_DOCS_GENERATOR = Path(freshness.__file__).resolve().parent / "generate_docs.py"


def test_vocabulary_book_never_mentions_the_internal_model_path() -> None:
    """The versioning policy calls ``_generated`` internal: users read ``niwaki.models``."""
    pages = sorted(_VOCABULARY_BOOK.rglob("*.md"))
    assert pages, f"no generated vocabulary pages under {_VOCABULARY_BOOK}"
    offenders = [
        str(page.relative_to(_REPO))
        for page in pages
        if _INTERNAL_PATH in page.read_text(encoding="utf-8")
    ]
    assert not offenders, f"generated docs point users at {_INTERNAL_PATH}: {offenders}"


def test_vocabulary_enums_page_points_at_the_public_enums_path() -> None:
    text = (_VOCABULARY_BOOK / "enums.md").read_text(encoding="utf-8")
    assert "niwaki.models.enums" in text


def test_docs_generator_never_emits_the_internal_model_path() -> None:
    """Checks emitted text only: the generator may still *import* from ``_generated``."""
    tree = ast.parse(_DOCS_GENERATOR.read_text(encoding="utf-8"))
    emitted = [
        (node.lineno, node.value)
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and _INTERNAL_PATH in node.value
    ]
    assert not emitted, f"generate_docs.py emits {_INTERNAL_PATH} at lines {emitted}"
